// Renders public/og.png (1200×630) with the real greeting renderer: node scripts/og-image.mjs [baseUrl]
import { chromium } from "playwright-core";
import { writeFileSync } from "node:fs";
const base = process.argv[2] ?? "http://localhost:5199";
const browser = await chromium.launch({ executablePath: "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome" });
const page = await browser.newPage({ viewport: { width: 1200, height: 630 } });
await page.goto(base + "/?t=1", { waitUntil: "networkidle" });
const dataUrl = await page.evaluate(async () => {
  const { GreetingRenderer, STAGE_SETTLE } = await import("/src/greeting/renderer.ts");
  const { MARK_PATH } = await import("/src/greeting/brand.ts");
  await document.fonts.load('700 80px "Eczar"', "Compile your light");
  await document.fonts.load('420 30px "Anek Latin"', "A Diwali greeting");
  await document.fonts.load('760 30px "Anek Latin"', "Interioring");
  const c = document.createElement("canvas");
  const r = new GreetingRenderer(c, "stage");
  r.stagePlaceholder = "";
  r.resize(1200, 630, { x: 620, y: 40, w: 560, h: 660 });
  r.setData({ recipientName: "", message: "", seed: 2026 });
  r.draw(STAGE_SETTLE);
  const ctx = c.getContext("2d");
  ctx.fillStyle = "#f4efe4";
  ctx.font = '700 84px "Eczar"';
  ctx.fillText("Compile", 72, 230);
  ctx.fillText("your light", 72, 318);
  ctx.fillStyle = "#d9c8b6";
  ctx.font = '420 30px "Anek Latin"';
  ctx.fillText("Make a Diwali 2026 greeting for someone:", 72, 392);
  ctx.fillText("a kolam drawn and diyas lit for their name.", 72, 432);
  ctx.save();
  ctx.translate(72, 512);
  ctx.scale(34 / 150, 34 / 150);
  ctx.fillStyle = "#a8907c";
  ctx.fill(new Path2D(MARK_PATH));
  ctx.restore();
  ctx.fillStyle = "#a8907c";
  ctx.font = '500 24px "Anek Latin"';
  ctx.fillText("Made with love by Interioring", 114, 538);
  return c.toDataURL("image/png");
});
writeFileSync("public/og.png", Buffer.from(dataUrl.split(",")[1], "base64"));
console.log("wrote public/og.png");
await browser.close();
